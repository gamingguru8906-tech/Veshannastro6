#!/usr/bin/env python3
"""Regenerate sitemap.xml from the pages that exist and are indexable.

Run from the repo root after adding, removing or editing pages:  python3 build-sitemap.py
lastmod is the date of the page's last commit, or today when the page has uncommitted changes.
"""
import datetime
import glob
import io
import re
import subprocess

BASE = "https://www.veshannastro.co.in/"
# India time: the site is run from Raipur, and a UTC date would lag by a day in the evening.
TODAY = datetime.datetime.now(datetime.timezone(datetime.timedelta(hours=5, minutes=30))).date().isoformat()

# Directory pages are listed by their folder address (the /index.html form redirects there).
PRIORITY = {
    "2027-numerology-report/index.html": ("1.0", "weekly"),
    "vedic-kundli-booking.html": ("0.9", "monthly"),
    "numerology-booking.html": ("0.9", "monthly"),
    "calculators/index.html": ("0.8", "monthly"),
    "blog/index.html": ("0.8", "weekly"),
    "vedic-astrologer-raipur.html": ("0.8", "monthly"),
    "about.html": ("0.6", "monthly"),
    "contact.html": ("0.6", "monthly"),
}
SECTION = {"blog/": ("0.7", "monthly"), "calculators/": ("0.7", "monthly")}
DEFAULT = ("0.4", "yearly")


def indexable(path):
    h = io.open(path, encoding="utf-8", errors="ignore").read()
    return not re.search(r'<meta name="robots"[^>]*noindex', h)


def lastmod(path):
    dirty = subprocess.run(["git", "status", "--porcelain", "--", path], capture_output=True, text=True).stdout.strip()
    if dirty:
        return TODAY
    day = subprocess.run(["git", "log", "-1", "--format=%cs", "--", path], capture_output=True, text=True).stdout.strip()
    return day or TODAY


def loc(path):
    return BASE + (path[: -len("index.html")] if path.endswith("index.html") else path)


pages = sorted(glob.glob("*.html") + glob.glob("2027-numerology-report/*.html") + glob.glob("blog/*.html") + glob.glob("calculators/*.html"))
urls = []
for f in pages:
    if not indexable(f):
        continue
    pr, cf = PRIORITY.get(f) or next((v for k, v in SECTION.items() if f.startswith(k)), DEFAULT)
    urls.append((loc(f), lastmod(f), cf, pr))
urls.sort(key=lambda u: (-float(u[3]), u[0]))

out = ['<?xml version="1.0" encoding="UTF-8"?>',
       '<!-- Veshannastro sitemap. Generated by build-sitemap.py; re-run it rather than editing by hand. -->',
       '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">']
for u, lm, cf, pr in urls:
    out += ["  <url>", f"    <loc>{u}</loc>", f"    <lastmod>{lm}</lastmod>", f"    <changefreq>{cf}</changefreq>", f"    <priority>{pr}</priority>", "  </url>"]
out.append("</urlset>")
io.open("sitemap.xml", "w", encoding="utf-8").write("\n".join(out) + "\n")
print("sitemap.xml: %d URLs" % len(urls))
for u, lm, _, pr in urls:
    print("  %-4s %s  %s" % (pr, lm, u))
